import assert from 'node:assert/strict';
import {InputFrameLatency} from '../preview/input_latency.js';
let now=1;
const profile=new InputFrameLatency({capacity:2,pendingLimit:2,now:()=>now});
profile.recordInput(); now=2; profile.recordInput();
now=3; profile.markSubmitted(); assert.equal(profile.snapshot().event_to_submit_ms,null);
now=4; profile.markDispatched(); assert.equal(profile.snapshot().dispatched,2);
now=10; profile.markSubmitted();
let report=profile.snapshot();
assert.equal(report.event_to_submit_ms.samples,2);
assert.equal(report.event_to_submit_ms.p50,9);
assert.equal(report.dispatch_to_submit_ms.p50,6);
profile.recordInput(); profile.recordInput(); profile.recordInput();
assert.equal(profile.snapshot().evicted,1);
profile.markDispatched(); profile.clearPending(); assert.equal(profile.snapshot().dispatched,0);
profile.reset(); report=profile.snapshot(); assert.equal(report.event_to_submit_ms,null); assert.equal(report.evicted,0);
assert.throws(()=>new InputFrameLatency({capacity:0}),RangeError);
assert.throws(()=>new InputFrameLatency({pendingLimit:0}),RangeError);
console.log('Bounded input-to-submission profiling tests passed.');
