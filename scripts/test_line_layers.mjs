import assert from 'node:assert/strict';
import {LineLayers, MAX_LINE_SEGMENTS} from '../preview/line_layers.js';
const layers=new LineLayers();
const line={start:[0,1,2],finish:[3,4,5],alpha:1};
assert.equal(layers.update({segments:[line]}),true);
assert.equal(layers.update({layer:'pursuit',segments:[{...line,color:[3,0.1,0.1]}]}),true);
assert.equal(layers.packed().length,20);
layers.update({layer:'pursuit',segments:[]});
assert.equal(layers.packed().length,10,'clearing one layer must retain the other');
layers.update({layer:'bad',segments:[{...line,color:[-1,0,0]},{...line,start:[NaN,0,0]}]});
assert.equal(layers.packed().length,10,'invalid geometry is ignored');
assert.equal(layers.update({layer:'invalid name',segments:[line]}),false);
layers.update({layer:'full',segments:Array(MAX_LINE_SEGMENTS+10).fill(line)});
assert.equal(layers.packed().length,MAX_LINE_SEGMENTS*10);
layers.clear(); assert.equal(layers.packed().length,0);
const box={center:[10,20,30],half_extents:[1,2,3],rotation:[0,1],color:[2,0.2,0.1],alpha:1};
assert.equal(layers.update({layer:'boxes',boxes:[box]}),true);
const packed=layers.packed();
assert.equal(packed.length,120,'each box has twelve edges');
assert.deepEqual([...packed.slice(0,6)],[13,18,29,7,18,29],'yaw rotation and world position are preserved');
layers.update({layer:'boxes',boxes:[{...box,rotation:[4,0]},{...box,half_extents:[-1,2,3]}]});
assert.equal(layers.packed().length,0,'invalid boxes cannot reach the GPU');

console.log('Independent colored line layers preserve each other and enforce rendering limits.');
